"""Face frame: an interpupillary-distance (ipd) based, roll-aware coordinate system.

Zones are defined once for the subject's RIGHT side with offsets in units of
ipd; the left side is generated by mirroring landmark indices (MIRROR) and
negating the horizontal offset. That makes zones scale with face size and
rotate with head roll.

"right"/"left" are the subject's sides (MediaPipe convention): the subject's
right eye is landmark 33/133/468 and appears on the image's left.
"""

from dataclasses import dataclass

import numpy as np

RIGHT_IRIS, LEFT_IRIS = 468, 473

# Subject right <-> subject left. Verified by the symmetry test on a real face.
MIRROR_PAIRS: list[tuple[int, int]] = [
    # eye contours
    (33, 263), (133, 362), (246, 466), (161, 388), (160, 387), (159, 386), (158, 385),
    (157, 384), (173, 398), (7, 249), (163, 390), (144, 373), (145, 374), (153, 380),
    (154, 381), (155, 382),
    # brows
    (70, 300), (63, 293), (105, 334), (66, 296), (107, 336),
    (46, 276), (53, 283), (52, 282), (65, 295), (55, 285),
    # lips (outer upper, outer lower, inner upper, inner lower)
    (61, 291), (185, 409), (40, 270), (39, 269), (37, 267),
    (146, 375), (91, 321), (181, 405), (84, 314),
    (78, 308), (191, 415), (80, 310), (81, 311), (82, 312),
    (95, 324), (88, 318), (178, 402), (87, 317),
    # face oval and jaw
    (234, 454), (93, 323), (132, 361), (58, 288), (172, 397), (136, 365), (150, 379),
    (149, 378), (176, 400), (148, 377), (127, 356), (162, 389), (21, 251), (54, 284),
    (103, 332), (67, 297), (109, 338),
    # nose / cheeks
    (129, 358), (98, 327), (205, 425), (50, 280), (123, 352),
    # irises
    (468, 473),
]
MIRROR: dict[int, int] = {}
for _r, _l in MIRROR_PAIRS:
    MIRROR[_r] = _l
    MIRROR[_l] = _r

# Indices on the face's vertical axis; they mirror onto themselves.
MIDLINE = [10, 152, 0, 13, 14, 17, 1, 4, 5, 6, 8, 9, 168, 197, 195, 2]


@dataclass(frozen=True)
class FaceFrame:
    pts: np.ndarray  # (478, 2) landmark pixels, image coordinates
    ipd: float
    u: np.ndarray  # unit vector, subject's right eye -> left eye (roll-aware)
    v: np.ndarray  # unit vector perpendicular to u, pointing down the face

    @staticmethod
    def from_landmarks(pts: np.ndarray) -> "FaceFrame":
        right, left = pts[RIGHT_IRIS], pts[LEFT_IRIS]
        d = left - right
        ipd = float(np.hypot(d[0], d[1]))
        if ipd < 1e-6:
            raise ValueError("Degenerate face: irises coincide")
        u = d / ipd
        # Image y grows downward, so rotating u by +90 degrees gives "down the face".
        v = np.array([-u[1], u[0]])
        return FaceFrame(pts=pts, ipd=ipd, u=u, v=v)

    @property
    def roll_degrees(self) -> float:
        return float(np.degrees(np.arctan2(self.u[1], self.u[0])))

    def point(self, index: int, du: float = 0.0, dv: float = 0.0, side: str = "right") -> np.ndarray:
        """Landmark `index` (defined for the subject's right) shifted by (du, dv) ipd.

        side="left" uses the mirrored landmark and negates du, so one definition
        yields both sides.
        """
        if side == "left":
            index = MIRROR.get(index, index)
            du = -du
        return self.pts[index] + self.ipd * (du * self.u + dv * self.v)

    def polygon(self, spec: list[tuple[int, float, float]], side: str = "right") -> np.ndarray:
        return np.array([self.point(i, du, dv, side) for i, du, dv in spec], dtype=np.float64)

    def indices(self, ids: list[int], side: str = "right") -> list[int]:
        return [MIRROR.get(i, i) if side == "left" else i for i in ids]
